# -*- coding: utf-8 -*-
"""Сшивка бесшовных петель из сгенерированных роликов площадок.

Генератор не гарантирует совпадения первого и последнего кадра: на пробном
ролике добычи расхождение вышло 3,2% пикселей, а это видимый рывок раз в пять
секунд — на стенде такое замечают сразу. Просить бесшовность у модели
бесполезно, зато движение техники на площадках обратимо по своей природе:
коромысло качалки, маховик задвижки, стрела эстакады. Поэтому петля собирается
зеркалом — прямой ход плюс обратный, и шов исчезает по построению.

Отклонённые варианты.

Кроссфейд последней секунды в первую. Требует двух видеоэлементов на площадку
и синхронизации между ними; на шести площадках это двенадцать декодеров в
кадре. Зеркало даёт тот же результат одним файлом.

Демультиплексор concat у ffmpeg. Падает на Windows с кодом 3221225477: он
читает пути из файла списка и спотыкается о кириллицу в них. Фильтр
filter_complex берёт входы аргументами, и вопрос путей отпадает.

Первый кадр обратного хода отбрасывается (trim=start_frame=1): иначе на стыке
последний кадр повторяется дважды и качание на мгновение залипает.
"""
import os
import subprocess
import sys

import numpy as np
from PIL import Image

ПАПКА = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'медиа', 'петли')


def сшить(код):
    """Собирает <код>_петля.mp4 из <код>.mp4 и возвращает величину шва."""
    исходный = os.path.join(ПАПКА, код + '.mp4')
    петля = os.path.join(ПАПКА, код + '_петля.mp4')
    if not os.path.exists(исходный):
        raise SystemExit('нет исходного ролика: ' + исходный)

    subprocess.run([
        'ffmpeg', '-y', '-loglevel', 'error', '-i', исходный, '-i', исходный,
        '-filter_complex',
        '[1:v]reverse,trim=start_frame=1[о];[0:v][о]concat=n=2:v=1:a=0[в]',
        '-map', '[в]', '-an', '-c:v', 'libx264', '-crf', '20',
        '-pix_fmt', 'yuv420p', петля], check=True)
    return петля, шов(петля)


def шов(петля):
    """Доля пикселей, расходящихся между первым и последним кадром, в процентах."""
    п = os.path.join(ПАПКА, '_п.png')
    к = os.path.join(ПАПКА, '_к.png')
    subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', петля,
                    '-vf', 'select=eq(n\\,0)', '-vframes', '1', п], check=True)
    subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-sseof', '-0.08',
                    '-i', петля, '-vframes', '1', к], check=True)
    a = np.asarray(Image.open(п).convert('L'), dtype=np.float64)
    b = np.asarray(Image.open(к).convert('L'), dtype=np.float64)
    os.remove(п)
    os.remove(к)
    return float((np.abs(a - b) > 12).mean() * 100)


def габарит(путь):
    """Габарит модуля внутри кадра, в долях кадра.

    Раскладка сцены считается из этих чисел, поэтому у площадки с петлёй его
    надо брать из кадра ролика: кадрирование у ролика своё, и от картинки оно
    отличается на проценты.
    """
    им = Image.open(путь)
    Ш, В = им.size
    м = np.asarray(им.convert('L'), dtype=np.float64) > 30
    сx = np.where(м.sum(axis=0) > 2)[0]
    сy = np.where(м.sum(axis=1) > 2)[0]
    return {'левый': round(100.0 * int(сx.min()) / Ш, 2),
            'правый': round(100.0 * int(сx.max()) / Ш, 2),
            'верх': round(100.0 * int(сy.min()) / В, 2),
            'низ': round(100.0 * int(сy.max()) / В, 2),
            'отн': round(Ш / float(В), 4)}


def габарит_петли(код):
    кадр = os.path.join(ПАПКА, '_кадр.png')
    subprocess.run(['ffmpeg', '-y', '-loglevel', 'error',
                    '-i', os.path.join(ПАПКА, код + '_петля.mp4'),
                    '-vf', 'select=eq(n\\,0)', '-vframes', '1', кадр], check=True)
    г = габарит(кадр)
    os.remove(кадр)
    return г


if __name__ == '__main__':
    коды = sys.argv[1:] or [и[:-4] for и in sorted(os.listdir(ПАПКА))
                            if и.endswith('.mp4') and not и.endswith('_петля.mp4')]
    for код in коды:
        петля, ш = сшить(код)
        мб = os.path.getsize(петля) / 1048576.0
        print('%-14s шов %.2f%%  %.1f МБ  габарит %s'
              % (код, ш, мб, габарит_петли(код)))
