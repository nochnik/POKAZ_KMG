# -*- coding: utf-8 -*-
"""Сборка сцены показа: фон плюс шесть площадок, разложенных по координатам.

Площадки генерируются по отдельности, и генератор не держит между ними единый
свет: замер 31.08 дал разброс средней яркости в 2,7 раза — добыча 157 против
геологии 57. Рядом друг с другом это читается как брак, поэтому яркость
выравнивается здесь, а не перегенерацией: перегенерация лотерейная, а
нормализация детерминированная и проверяется числом.

Вырезание фона делается порогом по яркости, а не remove_background: фон в
промпте задан чёрным намеренно, и порог даёт мягкую матовую кромку без
артефактов на рваных краях грунта.

ГЛУБИНА. Первая сборка вышла плоской, и заказчик это заметил. Разбор дал три
причины, из них одна — ошибка самой сборки:

1. Контактных теней не было вовсе. Площадка, наклеенная на фон без тени, висит,
   а не стоит. Это главная причина: ничто не связывает предмет с поверхностью.
2. Воздушной перспективы не было. Все шесть одинаково контрастны, тогда как
   удаление от зрителя обязано снижать контраст.
3. Нормализация яркости приводила все площадки к одному числу. Разброс 2,74 она
   вылечила, но заодно убрала светотеневую разницу, которая и давала объём.
   Теперь цель яркости не константа, а дуга: центральные площадки ближе к
   зрителю и ярче, крайние дальше и глуше.

Плюс ряд перестал быть прямой линией: центральные площадки чуть крупнее и чуть
ниже, крайние мельче и выше. Дуга слабая — шесть равных шагов обязаны остаться
равными, — но её хватает, чтобы ряд перестал читаться как аппликация.
"""
import os
import numpy as np
from PIL import Image, ImageDraw, ImageFilter

КОРЕНЬ = os.path.dirname(os.path.abspath(__file__))
СЦЕНА = os.path.join(КОРЕНЬ, 'медиа', 'сцена')

# Раскладка из спеки: доли от ширины сцены. Правится числом здесь,
# а не перегенерацией кадра — ради этого сборка и затевалась.
РАСКЛАДКА = [
    ('разведка',    0.09),
    ('геология',    0.25),
    ('добыча',      0.41),
    ('транспорт',   0.57),
    ('переработка', 0.73),
    ('сбыт',        0.89),
]
ШИРИНА_ПЛОЩАДКИ = 0.17   # доля ширины сцены, у центральной площадки
НИЗ_ПЛОЩАДКИ    = 0.78   # где стоит основание центральной площадки

# Дуга глубины. Ноль по краям, единица в середине.
ДУГА_МАСШТАБ = 0.07      # насколько центральные площадки крупнее крайних
ДУГА_СДВИГ   = 0.045     # насколько центральные ниже крайних, доля высоты
ЯРКОСТЬ_ЦЕНТР = 104.0    # цель яркости у ближней, центральной площадки
ЯРКОСТЬ_КРАЙ  = 74.0     # цель яркости у дальней, крайней
ДЫМКА_КРАЙ    = 0.16     # сколько фонового тона подмешивается крайним
СВЕТ_СТОЛА    = 46.0     # насколько подсвечивается пол под рядом


def дуга(центр):
    """1.0 в середине ряда, 0.0 по краям. Плавно, без изломов."""
    return 1.0 - (2.0 * abs(центр - 0.5)) ** 2


def вырезать(путь):
    """Матирует площадку с чёрного фона. Возвращает массив и альфу."""
    и = Image.open(путь).convert('RGB')
    a = np.asarray(и, dtype=np.float64)
    ярк = a.mean(axis=2)
    # мягкая кромка: ниже 10 — прозрачно, выше 35 — непрозрачно
    альфа = np.clip((ярк - 10.0) / 25.0, 0.0, 1.0)
    xs = np.where((альфа > 0.5).any(axis=0))[0]
    ys = np.where((альфа > 0.5).any(axis=1))[0]
    a = a[ys.min():ys.max()+1, xs.min():xs.max()+1]
    альфа = альфа[ys.min():ys.max()+1, xs.min():xs.max()+1]
    return a, альфа


def выровнять_яркость(a, альфа, цель):
    """Приводит среднюю яркость видимой части к заданной цели."""
    видно = альфа > 0.5
    if видно.sum() == 0:
        return a, 1.0
    текущая = a.mean(axis=2)[видно].mean()
    k = цель / max(текущая, 1.0)
    return np.clip(a * k, 0, 255), k


def подмешать_дымку(a, доля, тон):
    """Воздушная перспектива: дальнее теряет контраст, уходя в тон фона."""
    if доля <= 0:
        return a
    return a * (1.0 - доля) + np.array(тон, dtype=np.float64) * доля


def подсветить_стол(сцена, В):
    """Световое пятно на полу под рядом.

    Без него контактные тени бесполезны: чёрная тень на почти чёрном фоне не
    видна, и площадки продолжают висеть. Сначала нужен освещённый пол, на
    который есть что отбросить. В одном мастер-кадре это делал сам генератор —
    здесь делаем руками.
    """
    Ш = сцена.size[0]
    слой = Image.new('L', сцена.size, 0)
    рис = ImageDraw.Draw(слой)
    цy = int(В * (НИЗ_ПЛОЩАДКИ + 0.02))
    рис.ellipse([int(-Ш * 0.10), цy - int(В * 0.30),
                 int(Ш * 1.10),  цy + int(В * 0.30)], fill=255)
    слой = слой.filter(ImageFilter.GaussianBlur(int(Ш * 0.055)))

    a = np.asarray(сцена, dtype=np.float64)
    м = (np.asarray(слой, dtype=np.float64) / 255.0)[..., None]
    # подсветка холодная, в тон палитры: синего добавляем больше, красного меньше
    прибавка = np.array([0.55, 0.85, 1.25], dtype=np.float64) * СВЕТ_СТОЛА
    return Image.fromarray(np.clip(a + м * прибавка, 0, 255).astype(np.uint8))


def положить_тень(сцена, x, y, ш, в, сила):
    """Контактная тень под основанием. Без неё площадка висит, а не стоит."""
    слой = Image.new('L', сцена.size, 0)
    рис = ImageDraw.Draw(слой)
    цx = x + ш // 2
    цy = y + в - int(в * 0.03)
    rx = int(ш * 0.50)
    ry = max(4, int(в * 0.11))
    рис.ellipse([цx - rx, цy - ry, цx + rx, цy + ry], fill=int(255 * сила))
    слой = слой.filter(ImageFilter.GaussianBlur(max(4, int(ш * 0.045))))
    сцена.paste(Image.new('RGB', сцена.size, (0, 0, 0)), (0, 0), слой)


def собрать():
    фон = Image.open(os.path.join(СЦЕНА, 'фон.png')).convert('RGB')
    Ш, В = фон.size
    сцена = подсветить_стол(фон.copy(), В)
    # тон, в который уходит дальнее — берём из верхней трети фона
    тон_фона = np.asarray(фон, dtype=np.float64)[:В // 3].reshape(-1, 3).mean(axis=0)

    отчёт = []
    for код, центр in РАСКЛАДКА:
        д = дуга(центр)
        цель = ЯРКОСТЬ_КРАЙ + (ЯРКОСТЬ_ЦЕНТР - ЯРКОСТЬ_КРАЙ) * д
        дымка = ДЫМКА_КРАЙ * (1.0 - д)

        a, альфа = вырезать(os.path.join(СЦЕНА, 'площадка_%s.png' % код))
        a, k = выровнять_яркость(a, альфа, цель)
        a = подмешать_дымку(a, дымка, тон_фона)

        плитка = Image.fromarray(a.astype(np.uint8))
        маска = Image.fromarray((альфа * 255).astype(np.uint8))

        масштаб = 1.0 - ДУГА_МАСШТАБ * (1.0 - д)
        новая_ш = int(Ш * ШИРИНА_ПЛОЩАДКИ * масштаб)
        новая_в = int(плитка.height * новая_ш / плитка.width)
        плитка = плитка.resize((новая_ш, новая_в), Image.LANCZOS)
        маска = маска.resize((новая_ш, новая_в), Image.LANCZOS)

        x = int(Ш * центр) - новая_ш // 2
        y = int(В * (НИЗ_ПЛОЩАДКИ - ДУГА_СДВИГ * (1.0 - д))) - новая_в

        # тень кладётся до площадки, чтобы площадка встала поверх неё
        положить_тень(сцена, x, y, новая_ш, новая_в, 0.55 * (0.6 + 0.4 * д))
        сцена.paste(плитка, (x, y), маска)
        отчёт.append((код, k, цель, дымка, x, y, новая_ш))

    сцена.save(os.path.join(СЦЕНА, 'сцена.jpg'), 'JPEG',
               quality=88, optimize=True, progressive=True)
    return отчёт, (Ш, В)


if __name__ == '__main__':
    отчёт, размер = собрать()
    print(u'сцена %dx%d' % размер)
    print(u'%-14s %7s %8s %7s %7s %7s %7s'
          % (u'площадка', u'коэф.', u'цель', u'дымка', u'x', u'y', u'ширина'))
    for код, k, цель, дымка, x, y, ш in отчёт:
        print(u'%-14s %7.2f %8.0f %6.2f %8d %7d %7d'
              % (код, k, цель, дымка, x, y, ш))
